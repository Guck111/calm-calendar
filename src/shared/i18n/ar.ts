/** «بعد يومين», «بعد 3 أيام», «بعد 11 يومًا» — числительные в арабском требуют разных форм */
const days = (d: number): string => {
  if (d === 1) return "يوم واحد";
  if (d === 2) return "يومين";
  if (d <= 10) return `${d} أيام`;
  return `${d} يومًا`;
};

