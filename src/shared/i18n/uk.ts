/** 1 день, 2 дні, 5 днів */
const ukPlural = (n: number, [one, few, many]: string[]): string => {
  const d = n % 10;
  const dd = n % 100;
  if (d === 1 && dd !== 11) return one;
  if (d >= 2 && d <= 4 && (dd < 12 || dd > 14)) return few;
  return many;
};

const ukUnits: Record<Freq, string[]> = {
  DAILY: ["день", "дні", "днів"],
  WEEKLY: ["тиждень", "тижні", "тижнів"],
  MONTHLY: ["місяць", "місяці", "місяців"],
  YEARLY: ["рік", "роки", "років"],
};

/** у перший понеділок, у другу середу, в останню неділю */
const ukNth = (n: number, day: number): string => {
  const names = ["неділю", "понеділок", "вівторок", "середу", "четвер", "п'ятницю", "суботу"];
  const feminine = [true, false, false, true, false, true, true][day];
  const forms = [
    ["перший", "першу"],
    ["другий", "другу"],
    ["третій", "третю"],
    ["четвертий", "четверту"],
  ];
  const word = (n === -1 ? ["останній", "останню"] : forms[n - 1])[feminine ? 1 : 0];
  return `${word.startsWith("о") ? "в" : "у"} ${word} ${names[day]}`;
};

